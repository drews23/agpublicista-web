/* Prepare local pilot artifacts. No requests, accounts, API calls or publication. */
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const E=require('../js/ads-studio-engine.js');
const root=path.resolve(__dirname,'..');
const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures/ads-studio-pilot-2026-11-04.json'),'utf8'));
const destination=path.join(root,'output','ads-studio-pilot-2026-11-04');
fs.mkdirSync(destination,{recursive:true});
const checks=[];
for(const item of fixture.cases) {
  const draft=E.parseDraft(E.exportJson(item.draft));
  const analysis=E.analyze(draft);
  fs.writeFileSync(path.join(destination,item.id+'.json'),E.exportJson(draft)+'\n','utf8');
  fs.writeFileSync(path.join(destination,item.id+'.fuentes.json'),JSON.stringify({
    caseId:item.id,proposalOrigin:'Manually authored for this internal pilot; not generated by Ads Studio or Gemini.',
    source:item.source,metadata:{campaign:'not verified',adGroup:'not verified'},
    ownerSelectedDirection:fixture.directionDecision.caseIds.includes(item.id)?fixture.directionDecision:null,
    analysis,headlines:draft.headlines.map(a=>({text:a.text,units:E.countCharacters(a.text),pin:a.pin})),
    descriptions:draft.descriptions.map(a=>({text:a.text,units:E.countCharacters(a.text),pin:a.pin})),
    humanDecision:null,userTimeSeconds:null,corrections:null
  },null,2)+'\n','utf8');
  const texts=[item.id,'Propuesta manual para evaluación. No publicada.',draft.url,'',
    'TÍTULOS / HEADLINES',...draft.headlines.map((a,i)=>`${i+1}. ${a.text} (${E.countCharacters(a.text)}/30)`),'',
    'DESCRIPCIONES / DESCRIPTIONS',...draft.descriptions.map((a,i)=>`${i+1}. ${a.text} (${E.countCharacters(a.text)}/90)`),'',
    'Pendiente: revisión del responsable del negocio. Nombres de campaña y grupo sin verificar.',
    'El JSON conserva el borrador. El archivo .fuentes.json conserva la procedencia por separado.',
    'Sin datos de rendimiento, demanda, calidad publicitaria ni aprobación de políticas.'];
  fs.writeFileSync(path.join(destination,item.id+'.txt'),texts.join('\n')+'\n','utf8');
  checks.push({id:item.id,counts:analysis.counts,findings:analysis.findings,canExport:analysis.canExport});
}
const base=fixture.cases[0].draft;
const changes=[
  ['longitud',d=>{d.headlines[0].text='x'.repeat(31);},'ASSET_TOO_LONG'],
  ['url',d=>{d.url='javascript:alert(1)';},'FINAL_URL_INVALID'],
  ['duplicado',d=>{d.headlines[1].text=d.headlines[0].text.toUpperCase();},'ASSET_DUPLICATE'],
  ['gratuidad',d=>{d.headlines[0].text='Tu sitio web gratis';},'CLAIM_NOT_IN_LANDING'],
  ['destino-ausente',d=>{d.landing='';},'LANDING_NOT_PROVIDED'],
  ['busquedas-ausentes',d=>{d.terms='';},'TERMS_NOT_PROVIDED']
];
const controls=changes.map(([id,mutate,expected])=>{
  const draft=structuredClone(base);mutate(draft);const analysis=E.analyze(draft);
  return {id,expected,observed:analysis.findings.filter(f=>f.code===expected),passed:analysis.findings.some(f=>f.code===expected)};
});
const semanticDraft=structuredClone(fixture.cases[1].draft);
semanticDraft.headlines[1].text='Balayage sin daño';
const semantic=E.analyze(semanticDraft);
const safetyControl={
  id:'promesa-semantica-no-detectada',input:'Balayage sin daño',
  observed:semantic.findings,
  automatedSemanticValidation:false,
  explanation:'El motor no detecta esta promesa semántica. Requiere rechazo o corrección por revisión humana; no es una aprobación.',
  measuredCommercialQuality:false
};
fs.writeFileSync(path.join(destination,'comprobaciones.json'),JSON.stringify({
  preparedOn:fixture.date,cases:checks,controls,safetyControl,
  pilotStatus:'direction-reviewed-no-timed-task',ownerSelectedDirection:fixture.directionDecision,businessOwnerFinalCopyReview:'pending',
  userTimes:null,timeSavings:null,conversionResults:null,adsEditorImport:'not tested'
},null,2)+'\n','utf8');
const header='case_id,flow,status,user_start_iso,user_end_iso,user_seconds,preparation_seconds,corrections_fact,corrections_claim,corrections_tone,help_requests,owner_decision,notes';
const rows=fixture.cases.map(c=>[c.id,'lienzo','prepared',...Array(10).fill('')].join(','));
const register=path.join(destination,'registro-usuario.csv');
if(!fs.existsSync(register)) fs.writeFileSync(register,'\ufeff'+[header,...rows].join('\r\n')+'\r\n','utf8');
